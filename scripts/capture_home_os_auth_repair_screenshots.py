#!/usr/bin/env python3
"""Capture Home OS Marriott auth-repair PR screenshots (~1440px)."""

from __future__ import annotations

import os
import sys
import threading
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "pr-screenshots" / "home-os-auth-repair"
DB = ROOT / ".tmp-home-os-auth-repair-screenshots.db"
PORT = 8876


def main() -> int:
    sys.path.insert(0, str(ROOT))
    os.environ["SECRET_KEY"] = "home-os-auth-repair-screenshot-secret"
    os.environ["DEMO_MODE"] = "true"
    os.environ["HOME_OS_ENABLED"] = "true"
    os.environ["RAILWAY_ENVIRONMENT_NAME"] = "staging"
    os.environ["RAILWAY_ENVIRONMENT"] = "staging"
    os.environ.pop("MIGHTY_ENV", None)
    os.environ["DATABASE_PATH"] = str(DB)
    if DB.exists():
        DB.unlink()

    import app as mighty
    from werkzeug.serving import make_server

    mighty.DATABASE = str(DB)
    with mighty.app.app_context():
        mighty.init_db()

    OUT.mkdir(parents=True, exist_ok=True)

    server = make_server("127.0.0.1", PORT, mighty.app, threaded=True)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    time.sleep(0.4)

    from playwright.sync_api import sync_playwright

    base = f"http://127.0.0.1:{PORT}"
    try:
        with sync_playwright() as p:
            browser = p.chromium.launch()
            context = browser.new_context(
                viewport={"width": 1440, "height": 1100},
                device_scale_factor=2,
            )
            page = context.new_page()

            page.goto(f"{base}/research/home-os", wait_until="networkidle")
            page.wait_for_selector('[data-home-os="1"]')
            page.screenshot(path=str(OUT / "attention.png"), full_page=False)
            page.screenshot(path=str(OUT / "initial.png"), full_page=False)

            page.locator("button.home-os__primary").click()
            page.wait_for_selector("#home-os-repair-root:not([hidden])")
            page.screenshot(path=str(OUT / "opportunity.png"), full_page=False)
            page.screenshot(path=str(OUT / "interaction.png"), full_page=False)

            page.get_by_role("button", name="Sign-in didn't work").click()
            page.wait_for_selector('[data-repair-phase="failed"]')
            page.screenshot(path=str(OUT / "failure.png"), full_page=False)

            page.goto(f"{base}/research/home-os", wait_until="networkidle")
            page.locator("button.home-os__primary").click()
            page.wait_for_selector("#home-os-repair-root:not([hidden])")
            page.get_by_role("button", name="Confirm sign-in").click()
            page.wait_for_selector('[data-repair-phase="succeeded"]')
            page.screenshot(path=str(OUT / "all-clear.png"), full_page=False)
            page.screenshot(path=str(OUT / "success.png"), full_page=False)

            browser.close()
    finally:
        server.shutdown()

    (OUT / "README.md").write_text(
        """# Home OS — Marriott auth repair screenshots

Staging vertical slice: Marriott Interrupt resolved in place on Home.

**Do not embed these images in chat.** Open files from the repository.

## Required review trio

| File | What it shows |
|------|----------------|
| `attention.png` | Initial signed-out Marriott Interrupt on Home OS |
| `opportunity.png` | In-place repair modal open (interaction) |
| `all-clear.png` | Calm Home after successful repair + Marriott proof |

## Extra flow captures (requested for this slice)

| File | What it shows |
|------|----------------|
| `initial.png` | Same as attention — signed-out start |
| `interaction.png` | Same as opportunity — modal open |
| `success.png` | Same as all-clear — calm + proof |
| `failure.png` | Failed repair; Interrupt remains actionable |

Generated by `scripts/capture_home_os_auth_repair_screenshots.py`.
""",
        encoding="utf-8",
    )
    print(f"Wrote screenshots to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
